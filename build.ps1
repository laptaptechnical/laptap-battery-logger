# build.ps1 (dev only; staff never run this)
# 0) version from VERSION → src/Version.g.cs + src/app.manifest; no version literal anywhere else in src/
# 1) node tests  2) compile the logger exe with the built-in .NET Framework csc (C# 5)
# 3) run-from-removable-media PE flags  4) FileVersion = VERSION; a release build has no test hooks
# 5) compile + run HelperTests.exe  6) the output folder holds exactly one exe, < 400 KB.
# Installs nothing. Fails on the first failing step.
param(
    [string]$Out = 'dist',      # e.g. -Out dist-next to leave a frozen dist alone
    [string]$Version,           # override VERSION (tests / release.ps1 only)
    [int]$Release = 0,          # override VERSION's release
    [switch]$TestHooks,         # /define:TESTHOOKS: local test server + /api/start hook. Never released.
    [switch]$SkipTests,         # compile only (the update end-to-end test builds two throwaway exes)
    [switch]$AllowNoKeys        # dev builds only: allow fewer than 2 signing keys (that exe can never self-update)
)
$ErrorActionPreference = 'Stop'
Set-Location -LiteralPath $PSScriptRoot

$csc = Join-Path $env:WINDIR 'Microsoft.NET\Framework64\v4.0.30319\csc.exe'
if (-not (Test-Path -LiteralPath $csc)) { $csc = Join-Path $env:WINDIR 'Microsoft.NET\Framework\v4.0.30319\csc.exe' }
if (-not (Test-Path -LiteralPath $csc)) { throw 'csc.exe (.NET Framework 4) not found' }

function Step($name) { Write-Host ''; Write-Host "== $name" }
$outDir = if ([IO.Path]::IsPathRooted($Out)) { $Out } else { Join-Path $PSScriptRoot $Out }
$exe = Join-Path $outDir 'Laptap Battery Logger.exe'
$refs = @('/r:System.Management.dll', '/r:System.Web.Extensions.dll', '/r:System.Windows.Forms.dll', '/r:System.Core.dll')

# ---- 0. version from one place (E8) ----
Step 'version'
$vf = @{}
foreach ($line in Get-Content -LiteralPath (Join-Path $PSScriptRoot 'VERSION')) {
    if ($line -match '^\s*(\w+)\s*=\s*(\S+)\s*$') { $vf[$Matches[1]] = $Matches[2] }
}
$ver = if ($Version) { $Version } else { $vf['version'] }
$rel = if ($Release -gt 0) { $Release } else { [int]$vf['release'] }
if ($ver -notmatch '^\d+\.\d+\.\d+$' -or $rel -lt 1) { throw "VERSION must hold version=X.Y.Z and release=N (got '$ver', '$rel')" }
$buildMs = [DateTimeOffset]::UtcNow.ToUnixTimeMilliseconds()
$gen = @"
// src/Version.g.cs — GENERATED by build.ps1 from VERSION. Do not edit; not committed.
using System.Reflection;
[assembly: AssemblyVersion("$ver.0")]
[assembly: AssemblyFileVersion("$ver.0")]
[assembly: AssemblyInformationalVersion("$ver")]
public static class AppVersion
{
    public const string Version = "$ver";
    public const int Release = $rel;
    public const long BuildDateUtcMs = $buildMs;
}
"@
[IO.File]::WriteAllText((Join-Path $PSScriptRoot 'src\Version.g.cs'), $gen, (New-Object Text.UTF8Encoding($false)))
$man = (Get-Content -LiteralPath (Join-Path $PSScriptRoot 'src\app.manifest.in') -Raw).Replace('@VERSION4@', "$ver.0")
[IO.File]::WriteAllText((Join-Path $PSScriptRoot 'src\app.manifest'), $man, (New-Object Text.UTF8Encoding($false)))
Write-Host "version $ver, release $rel$(if ($TestHooks) { ' (TESTHOOKS)' })"

# No other version literal in src/ (M2): Version.g.cs is the only home.
$lit = Get-ChildItem -LiteralPath (Join-Path $PSScriptRoot 'src') -Recurse -File -Include *.cs, *.html, *.js |
    Where-Object { $_.Name -ne 'Version.g.cs' } |
    Select-String -Pattern '["'']v?\d+\.\d+\.\d+["'']'
if ($lit) { throw ('version literal outside Version.g.cs: ' + (($lit | ForEach-Object { "$($_.Filename):$($_.LineNumber)" }) -join ', ')) }

# B1: an exe handed out without the owner's two public keys can never self-update. Refuse it.
if (-not $TestHooks) {
    $uk = Get-Content -LiteralPath (Join-Path $PSScriptRoot 'src\UpdateKeys.cs') -Raw
    $nk = ([regex]::Matches($uk, 'new string\[\]\s*\{\s*"[0-9a-fA-F]{64}"\s*,\s*"[0-9a-fA-F]{64}"\s*\}')).Count
    if ($nk -lt 2) {
        if ($AllowNoKeys) { Write-Warning "DEV BUILD: src\UpdateKeys.cs holds $nk signing key(s). This exe can never self-update. Never hand it out." }
        else { throw "src\UpdateKeys.cs holds $nk signing key(s); a release build needs the owner's 2 (tools\keys.ps1 new). Use -AllowNoKeys for a dev build only." }
    } else { Write-Host "$nk signing keys in UpdateKeys.cs" }
}

$src = Get-ChildItem -LiteralPath (Join-Path $PSScriptRoot 'src') -Filter *.cs | ForEach-Object { $_.FullName }
$defs = if ($TestHooks) { @('/define:TESTHOOKS') } else { @() }

# ---- 1. node tests ----
if (-not $SkipTests) {
    Step 'node tests (logic.js)'
    $node = Get-Command node -ErrorAction SilentlyContinue
    if ($node) {
        & $node.Source --test (Join-Path $PSScriptRoot 'tests')
        if ($LASTEXITCODE -ne 0) { throw 'node tests failed' }
    } else { Write-Warning 'node not found: logic.js tests skipped' }
}

# ---- 2. compile the logger ----
Step 'compile Laptap Battery Logger.exe'
New-Item -ItemType Directory -Force -Path $outDir | Out-Null
$cargs = @('/nologo', '/target:winexe', '/platform:anycpu', '/optimize+', '/win32icon:src\laptap.ico', '/win32manifest:src\app.manifest') + $refs + $defs +
        @('/resource:src\web\index.html,index.html', '/resource:src\web\logic.js,logic.js', "/out:$exe") + $src
& $csc @cargs
if ($LASTEXITCODE -ne 0) { throw 'compile failed (logger)' }

# ---- 3. PE flags: IMAGE_FILE_REMOVABLE_RUN_FROM_SWAP (0x0400) + IMAGE_FILE_NET_RUN_FROM_SWAP (0x0800) ----
Step 'set run-from-swap PE flags'
$b = [System.IO.File]::ReadAllBytes($exe)
$pe = [BitConverter]::ToInt32($b, 0x3C)
if ($b[$pe] -ne 0x50 -or $b[$pe + 1] -ne 0x45 -or $b[$pe + 2] -ne 0 -or $b[$pe + 3] -ne 0) { throw 'not a PE file' }
$ch = [BitConverter]::ToUInt16($b, $pe + 22) -bor 0x0C00
$bytes = [BitConverter]::GetBytes([uint16]$ch)
$b[$pe + 22] = $bytes[0]; $b[$pe + 23] = $bytes[1]
[System.IO.File]::WriteAllBytes($exe, $b)
$check = [BitConverter]::ToUInt16([System.IO.File]::ReadAllBytes($exe), $pe + 22)
if (($check -band 0x0C00) -ne 0x0C00) { throw 'PE flags not set' }
Write-Host ('Characteristics = 0x{0:X4}' -f $check)

# ---- 4. version + release-build checks ----
Step 'version / test-hook checks'
$fv = [Diagnostics.FileVersionInfo]::GetVersionInfo($exe).FileVersion
if ($fv -ne "$ver.0") { throw "FileVersion is '$fv', VERSION says '$ver'" }
Write-Host "FileVersion $fv"
if (-not $TestHooks) {
    $raw = [IO.File]::ReadAllBytes($exe)
    $latin = [Text.Encoding]::GetEncoding(28591).GetString($raw)
    $utf16 = [Text.Encoding]::Unicode.GetString($raw) + [Text.Encoding]::Unicode.GetString($raw, 1, $raw.Length - 1)
    foreach ($needle in @('LAPTAP_BL_TEST_BASE', 'LAPTAP_BL_TEST_PUBKEYS', 'LAPTAP_BL_TEST_NS', '/api/start')) {
        if ($latin.Contains($needle) -or $utf16.Contains($needle)) { throw "release exe contains test hook text: $needle" }
    }
    Write-Host 'no test hooks in the release exe'
}

# ---- 5. C# tests ----
if (-not $SkipTests) {
    Step 'compile + run HelperTests.exe'
    $tbin = Join-Path $PSScriptRoot 'tests\bin'
    New-Item -ItemType Directory -Force -Path $tbin | Out-Null
    $texe = Join-Path $tbin 'HelperTests.exe'
    $targs = @('/nologo', '/target:exe', '/platform:anycpu', '/main:HelperTests', '/define:TESTHOOKS') + $refs +
             @('/resource:src\web\index.html,index.html', '/resource:src\web\logic.js,logic.js', "/out:$texe") + $src +
             @('tools\KeyTools.cs', 'tests\V15Tests.cs', 'tests\V151Tests.cs', 'tests\HelperTests.cs')
    & $csc @targs
    if ($LASTEXITCODE -ne 0) { throw 'compile failed (tests)' }
    & $texe (Join-Path $PSScriptRoot 'tests\fixtures') $exe (Join-Path $PSScriptRoot 'src\web\index.html')
    if ($LASTEXITCODE -ne 0) { throw 'HelperTests failed' }
}

# ---- 6. output check ----
Step 'output check'
$files = @(Get-ChildItem -LiteralPath $outDir -Force)
if ($files.Count -ne 1) { throw ($Out + '\ must hold exactly one file, found: ' + (($files | ForEach-Object Name) -join ', ')) }
$kb = [Math]::Round((Get-Item -LiteralPath $exe).Length / 1KB, 1)
Write-Host "$Out\Laptap Battery Logger.exe = $kb KB"
if ($kb -ge 400) { throw "exe is $kb KB (target < 400 KB)" }
Write-Host ''
Write-Host 'BUILD OK'
